#!/usr/bin/env python3
"""Cost model for the Prolific listening test (Amazon Mechanical Turk closed on 2026-09-30).

Inputs come from config/design.json. Fee rates are the ones on Prolific's pricing help page
(https://researcher-help.prolific.com/en/articles/445239-what-is-your-pricing, dated 2026-10-09):
platform fee = 42.857% of participant rewards (corporate) or 33.33% (academia/non-profit; needs an
institutional e-mail address). VAT applies to the fee only; the 19% used for the sensitivity column is
the German standard rate and is an assumption, not a Prolific figure.

    python3 scripts/cost_model.py [--out results/cost_table.md]
"""
import argparse, json, math, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CFG = json.loads((ROOT / "config" / "design.json").read_text())

def session_minutes(cfg=CFG):
    t, K = cfg["timing_s"], cfg["tiles_per_listener"]
    n_dcr = K * len(cfg["systems"]) + 2 + cfg["trapping_items"]   # test items + 2 CRIPPLED gold + trapping
    secs = (n_dcr * t["dcr_item"] + cfg["ab_trials_per_listener"] * t["ab_item"]
            + cfg["training_clips"] * t["training_item"] + t["consent_instructions"])
    return secs * (1 + t["slack_fraction"]) / 60.0, n_dcr

def reward(minutes, hourly):
    return math.ceil(hourly * minutes / 60.0 * 20) / 20.0      # round up to GBP 0.05

def scenario(L_eligible, cfg=CFG):
    A, P, Pr = cfg["assumptions"], cfg["pay"], cfg["prolific"]
    m_main, n_dcr = session_minutes(cfg)
    m_scr = cfg["timing_s"]["screener_total"] / 60.0
    r_main, r_scr = reward(m_main, P["hourly_gbp"]), reward(m_scr, P["hourly_gbp"])
    n_main = math.ceil(L_eligible / (1 - A["main_exclusion_rate"]))
    n_scr = math.ceil(n_main / A["screener_pass_rate"])
    rewards = n_main * r_main + n_scr * r_scr
    out = {"L": L_eligible, "n_main": n_main, "n_scr": n_scr, "r_main": r_main, "r_scr": r_scr,
           "m_main": m_main, "m_scr": m_scr, "rewards": rewards}
    for k, f in (("corp", Pr["fee_corporate"]), ("acad", Pr["fee_academic"])):
        out[k] = rewards * (1 + f)
        out[k + "_vat"] = rewards * (1 + f + f * Pr["vat_on_fee_assumed"])
    return out

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "results" / "cost_table.md"))
    a = ap.parse_args()
    P, Pr = CFG["pay"], CFG["prolific"]
    g = P["ecb_gbp_per_eur_2026_11_17"]
    floor_gbp = P["german_min_wage_eur_per_hour_2026"] * g
    m_main, n_dcr = session_minutes()
    pilot = scenario(10)
    lines = ["# Cost model (Prolific)", "",
             "Generated by `scripts/cost_model.py` from `config/design.json`. Times and rates are plans, not measurements; the pilot replaces them.", "",
             f"* German statutory minimum wage 2026: EUR {P['german_min_wage_eur_per_hour_2026']:.2f}/h (https://www.bmas.de/DE/Service/Presse/Pressemitteilungen/2025/anhebung-gesetzlicher-mindestlohn-zum-1-1-2026.html; rises to EUR 14.60 on 2027-01-01 per MiLoV5).",
             f"* ECB reference rate 2026-11-17: 1 EUR = {g} GBP, so the floor is GBP {floor_gbp:.2f}/h; the plan pays GBP {P['hourly_gbp']:.2f}/h (= EUR {P['hourly_gbp']/g:.2f}/h), Prolific's own minimum is GBP {Pr['min_gbp_per_hour']:.2f}/h and its recommendation GBP {Pr['recommended_gbp_per_hour']:.2f}/h.",
             f"* Main session: {n_dcr} DCR items + {CFG['ab_trials_per_listener']} A/B + {CFG['training_clips']} training clips = {m_main:.1f} min including {int(CFG['timing_s']['slack_fraction']*100)}% slack; screener {CFG['timing_s']['screener_total']/60:.0f} min.",
             f"* Assumptions: screener pass rate {CFG['assumptions']['screener_pass_rate']:.0%}, post-hoc exclusion rate {CFG['assumptions']['main_exclusion_rate']:.0%}.",
             "* Julian is an independent researcher with a personal e-mail address, so the corporate fee (42.857%) is the planning case; the academic fee (33.33%) needs an institutional address and the Academia account type.",
             "* Prolific states VAT is charged on the platform fee only, depending on where the account is based. The `+VAT` columns assume 19% on the fee (German standard rate, assumption).",
             "* All amounts GBP (Prolific workspace in GBP). Amazon Mechanical Turk is not an option: it closed on 2026-09-30.", "",
             "| analysable listeners | recruited main | screener participants | reward main | reward screener | total rewards | total corporate | corporate + VAT | total academic | EUR corporate |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for L in (10, 40, 60, 100):
        s = scenario(L)
        label = f"{L} (pilot)" if L == 10 else str(L)
        lines.append(f"| {label} | {s['n_main']} | {s['n_scr']} | {s['r_main']:.2f} | {s['r_scr']:.2f} | {s['rewards']:.2f} | {s['corp']:.2f} | {s['corp_vat']:.2f} | {s['acad']:.2f} | {s['corp']/g:.2f} |")
    lines += ["", "Pilot (10 analysable listeners) should run first, with the whole pipeline, before the main sample is bought.",
              "", "## Historical MTurk fee schedule (for the record only)",
              "From https://requester.mturk.com/pricing (page now states the service is closed): 20% commission on reward and bonus, plus another 20% for HITs with 10 or more assignments (40% in total for this study), 5% extra for Masters, 0.01 USD minimum per assignment."]
    pathlib.Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(a.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))

if __name__ == "__main__":
    main()
