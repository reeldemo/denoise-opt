#!/usr/bin/env python3
"""Simulation-based power for the DenoiseOpt listening test (crossed listeners x tiles).

Primary contrast: mean DCR difference between two systems (e.g. OURS - N2N), analysed with a
two-way cluster-robust t test (Cameron-Gelbach-Miller; listeners and tiles are the clusters,
df = min(#listeners, #tiles) - 1). Variance components are ASSUMPTIONS from config/design.json
and must be replaced by estimates from the pilot. Nothing here is a measured result.

    python3 scripts/power_analysis.py [--nrep 2000] [--out results/power_table.md]
"""
import argparse, json, pathlib
import numpy as np
from scipy import stats

CFG = json.loads((pathlib.Path(__file__).resolve().parent.parent / "config" / "design.json").read_text())

def cgm_t(d, li, ti, L, T):
    """Two-way cluster-robust t statistic for the mean of d."""
    n = d.size
    beta = d.mean()
    r = d - beta
    s_l = np.bincount(li, weights=r, minlength=L)
    s_t = np.bincount(ti, weights=r, minlength=T)
    v_l = (s_l ** 2).sum() / n ** 2
    v_t = (s_t ** 2).sum() / n ** 2
    v_lt = (r ** 2).sum() / n ** 2          # one observation per listener x tile
    v = v_l + v_t - v_lt
    if v <= 0:                                # CGM can be non-positive; fall back to the larger one-way variance
        v = max(v_l, v_t)
    return beta / np.sqrt(v)

def power(L, T, K, delta, sl, st, se, nrep, rng, alpha=0.05):
    df = min(L, T) - 1
    crit = stats.t.ppf(1 - alpha / 2, df)
    hit = 0
    for _ in range(nrep):
        # each listener rates K distinct tiles (independent draws: slightly more imbalance than the real balanced design)
        ti = np.array([rng.choice(T, K, replace=False) for _ in range(L)])
        li = np.repeat(np.arange(L), K); tj = ti.ravel()
        a = rng.normal(0, np.sqrt(2) * sl, L)[li]
        b = rng.normal(0, np.sqrt(2) * st, T)[tj]
        e = rng.normal(0, np.sqrt(2) * se, L * K)
        d = delta + a + b + e
        if abs(cgm_t(d, li, tj, L, T)) > crit:
            hit += 1
    return hit / nrep

def ab_power(n_listeners, trials_each, p_true, icc, alpha=0.05):
    """Exact two-sided binomial power on the effective number of independent trials."""
    de = 1 + (trials_each - 1) * icc
    n = int(round(n_listeners * trials_each / de))
    ks = np.arange(n + 1)
    pv = np.array([stats.binomtest(int(k), n, 0.5).pvalue for k in ks])
    return float(stats.binom.pmf(ks, n, p_true)[pv < alpha].sum()), n

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nrep", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=20261118)
    ap.add_argument("--out", default=str(pathlib.Path(__file__).resolve().parent.parent / "results" / "power_table.md"))
    a = ap.parse_args()
    rng = np.random.default_rng(a.seed)
    A = CFG["assumptions"]; K = CFG["tiles_per_listener"]
    scen = {"assumed": (A["sigma_listener_x_system"], A["sigma_tile_x_system"], A["sigma_residual"]),
            "pessimistic": (A["sigma_pessimistic"]["listener_x_system"], A["sigma_pessimistic"]["tile_x_system"], A["sigma_pessimistic"]["residual"])}
    Ls, Ts, deltas = [20, 40, 60, 100, 150], [12, 24, 48], [0.2, 0.3, 0.5]
    lines = ["# Power table (simulated, ASSUMED variance components)", "",
             f"Generated by `scripts/power_analysis.py`, seed {a.seed}, {a.nrep} simulations per cell, two-sided alpha = 0.05, K = {K} tiles rated per listener.",
             "Power = P(reject H0: no DCR difference between the two systems). Delta is the true DCR-point difference (5-point scale).",
             "Variance components are placeholders (design.json `assumptions`); replace them with pilot estimates before relying on any cell.", ""]
    for name, (sl, st, se) in scen.items():
        lines += [f"## Scenario `{name}`: sigma_listener x system = {sl}, sigma_tile x system = {st}, sigma_residual = {se}", "",
                  "| listeners L | tiles T | " + " | ".join(f"power at delta={d}" for d in deltas) + " | type-I error (delta=0) |",
                  "|---|---|" + "---|" * (len(deltas) + 1)]
        for L in Ls:
            for T in Ts:
                if K > T: continue
                ps = [power(L, T, K, d, sl, st, se, a.nrep, rng) for d in deltas]
                t1 = power(L, T, K, 0.0, sl, st, se, a.nrep, rng)
                lines.append(f"| {L} | {T} | " + " | ".join(f"{p:.2f}" for p in ps) + f" | {t1:.3f} |")
        lines.append("")
    lines += ["## Forced-choice A/B (OURS vs N2N), exact binomial on effective trials", "",
              f"{CFG['ab_trials_per_listener']} trials per listener; intra-listener correlation ICC = {A['ab_icc']} (assumption) gives design effect 1 + (m-1) ICC.",
              "'No audible difference' answers are dropped before the test (so the effective n is smaller if they are frequent).", "",
              "| listeners | effective n | p(prefer OURS) = 0.55 | 0.60 | 0.65 | 0.70 |", "|---|---|---|---|---|---|"]
    m = CFG["ab_trials_per_listener"]
    for L in Ls:
        row, neff = [], None
        for p in (0.55, 0.60, 0.65, 0.70):
            pw, neff = ab_power(L, m, p, A["ab_icc"]); row.append(f"{pw:.2f}")
        lines.append(f"| {L} | {neff} | " + " | ".join(row) + " |")
    pathlib.Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(a.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))

if __name__ == "__main__":
    main()
