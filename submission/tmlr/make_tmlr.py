#!/usr/bin/env python3
"""Build the TMLR-format package for the DenoiseOpt paper from the repository sources.

Reads  ../../main.tex, ../../subsections/*.tex, ../../figures/*  (never modifies them) and writes into
this directory: main.tex, subsections/, figures/ (only files the paper actually uses).

    python3 submission/tmlr/make_tmlr.py            # anonymous review variant
    python3 submission/tmlr/make_tmlr.py --accepted # camera-ready variant (author block, links kept)

Scientific text is not edited. Changed: preamble, title/abstract block, citation commands and
bibliography labels, starred floats, and (review variant only) identifying links/names.
"""
import re, shutil, sys, pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
ACC = "--accepted" in sys.argv
src = (ROOT / "main.tex").read_text(encoding="utf-8")

# ---------------------------------------------------------------- abstract
abs_m = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", src, re.S)
abstract = abs_m.group(1).strip()

# ---------------------------------------------------------------- body after the title block
body = src[src.index(r"\input{subsections/introduction}"):]
body = body.replace("\\FloatBarrier\n\\balance\n", "\\FloatBarrier\n")
body = re.sub(r"\\begin\{(figure|table|algorithm)\*\}", r"\\begin{\1}", body)
body = re.sub(r"\\end\{(figure|table|algorithm)\*\}", r"\\end{\1}", body)

# bibliography: author-year labels for natbib (tmlr.sty uses authoryear)
def label(entry_head, year):
    first_line = entry_head.strip().split("\n")[0]
    names = re.split(r",\s+and\s+|\s+and\s+|,\s+", first_line.rstrip("."))
    names = [n for n in names if n and not n.startswith("et")]
    et_al = "et al" in first_line or len(names) >= 3
    def sur(n):
        n = n.replace("et~al", "").replace("et al", "").strip().rstrip(".")
        parts = re.split(r"~|\s", n)
        return parts[-1] if parts else n
    s1 = sur(names[0]) if names else "Anon"
    if et_al:
        return f"{s1} et~al.({year})"
    if len(names) == 2:
        return f"{s1} and {sur(names[1])}({year})"
    return f"{s1}({year})"

def relabel(m):
    key, rest = m.group(1), m.group(2)
    clean = re.sub(r"arXiv:\S+|https?://\S+|\\url\{[^}]*\}|\\href\{[^}]*\}", " ", rest)
    years = re.findall(r"\b(?:19|20)\d{2}\b", clean)
    year = years[-1] if years else "n.d."
    return "\\bibitem[%s]{%s}%s" % (label(rest, year), key, rest)
body = re.sub(r"\\bibitem\{([^}]+)\}(.*?)(?=\\bibitem\{|\\end\{thebibliography\})", relabel, body, flags=re.S)
body = body.replace("\\cite{", "\\citep{")
# \cite{} -> \citep{} globally happens below for subsections too

# ---------------------------------------------------------------- preamble
head = r"""% Auto-generated by make_tmlr.py from ../../main.tex -- do not edit by hand.
\documentclass[10pt]{article}
\usepackage[@OPT@]{tmlr}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{tabularx}
\usepackage{adjustbox}
\usepackage[section]{placeins}
\usepackage{amsmath,amssymb,amsthm}
\usepackage{algorithm}
\usepackage{algpseudocode}
\usepackage{float}
\usepackage{tikz}
\usetikzlibrary{arrows.meta,positioning}
\usepackage{xurl}
\usepackage[colorlinks=true,linkcolor=blue,citecolor=blue,urlcolor=blue]{hyperref}
\usepackage{xstring}
\newtheorem{proposition}{Proposition}
\newtheorem{lemma}{Lemma}
\theoremstyle{remark}
\newtheorem{remark}{Remark}
\newcommand{\papershorttitle}{Wavetable Wrap-Discontinuity Repair}
\newcommand{\keywords}[1]{}
""".replace("@OPT@", "accepted" if ACC else "")

if not ACC:
    head += r"""% double-blind: links into the author's repositories are shown as plain text only
\let\origurl\url
\let\orighref\href
\renewcommand{\href}[2]{\IfSubStr{#1}{reeldemo}{#2}{\orighref{#1}{#2}}}
"""

# LLM-use footnote on the first page (TMLR FAQ). Wording approved by Julian (2026-11-18, 09:01); keep verbatim,
# identical in the review and the accepted variant. "Section 8" is \\ref{sec:tooling} (checked against the PDF).
AI_NOTE = ("The author used AI coding, research and writing assistants (Cursor, Grok Bot, Hermes Agent, Antigravity and "
           "SciSpace) to write code, run experiments, search and read literature, and draft and edit text. The research "
           "questions, study design and conclusions are the author's. The author checked every number against the released "
           "result files and every citation against its source, and takes full responsibility for the content. "
           "Tools used are listed in Section~\\ref{sec:tooling} (Tooling and AI use).")

# Double-blind review name of the method. The public repository, the named paper and the accepted variant keep
# "DenoiseOpt"; only the review variant says "HybridSeam" (hybrid GA+PPO search over seam-local repair operators).
REVIEW_NAME = "HybridSeam"
def review_rename(t):
    t = t.replace("DenoiseOpt", REVIEW_NAME).replace("denoiseopt", REVIEW_NAME.lower())
    return t
title = r"""\title{Seam-Local Repair of Wavetable Wrap Discontinuities with a Self-Supervised Blended Residual}"""
if ACC:
    author = r"\author{\name Julian M. Kleber \email julian.m.kleber@gmail.com \\ \addr Independent Researcher, ORCID 0000-0001-5518-0932}"
else:
    author = r"\author{\name Anonymous authors \\ \addr Paper under double-blind review}"
# Thin space before the LLM footnote so "Section 5." + superscript 1 is not read as "5.1" in PDF text.
abs_body = (abstract if ACC else review_rename(abstract)).rstrip()
pre_doc = "\n".join([
    title, author,
    r"\def\month{MM}  % camera-ready only", r"\def\year{YYYY} % camera-ready only",
    r"\def\openreview{\url{https://openreview.net/forum?id=XXXX}} % camera-ready only",
    r"\begin{document}", r"\maketitle", r"\begin{abstract}", abs_body + "\\,\\footnote{" + AI_NOTE + "}", r"\end{abstract}", "",
])

# ---------------------------------------------------------------- subsections / figures
out_sub = HERE / "subsections"; out_fig = HERE / "figures"
for d in (out_sub, out_fig):
    if d.exists(): shutil.rmtree(d)
    d.mkdir()

def anonymise(t):
    if ACC: return t
    t = review_rename(t)
    t = re.sub(r"\\href\{https?://github\.com/reeldemo[^}]*\}\{([^}]*)\}", r"\1", t)
    t = re.sub(r"\\url\{https?://github\.com/reeldemo[^}]*\}", r"\\textit{[anonymized repository]}", t)
    t = t.replace("Julian~M.~Kleber", "The author")
    t = t.replace("(reeldemo/denoise-opt)", "(anonymized repository)")
    t = re.sub(r"^%.*reeldemo.*\n", "", t, flags=re.M)
    # project names identify the author: neutral wording in the review variant
    t = t.replace("ReelSynth and denoise-opt are public repositories maintained by the author. ", "")
    t = re.sub(r"\\href\{https?://github\.com/reeldemo/reelsynth\}\{ReelSynth repository\}", "host synthesizer's repository", t)
    for a, b in (("in the ReelSynth repository", "in the host synthesizer's repository"),
                 ("used by ReelSynth", "used by the host synthesizer"),
                 ("ReelSynth-exported", "synthesizer-exported"),
                 ("ReelSynth Factory+FX", "host-synthesizer Factory+FX"),
                 ("ReelSynth factory", "host-synthesizer factory"),
                 ("ReelSynth exports", "host-synthesizer exports"),
                 ("ReelSynth export", "host-synthesizer export")):
        t = t.replace(a, b)
    t = t.replace("ReelSynth", "the host synthesizer")
    # CRediT block names the single author
    t = re.sub(r"\\subsection\{Author contributions \(CRediT\)\}\n\\label\{sec:credit\}\n[^\n]*\n", "", t)
    t = t.replace(
        "(see \\texttt{LICENSE} and \\texttt{LICENSE-text} in the repository named in Section~\\ref{sec:data-availability}).",
        "(licence files accompany the anonymized supplementary material; see Section~\\ref{sec:data-availability}).",
    )
    # Broader impact / reproducibility (sec:ethics): supplementary ZIP renames the code tree to hybridseam/HostSynth.
    t = t.replace(
        "Paper sources, frozen figure JSONs, and build scripts live at\n"
        "\\textit{[anonymized repository]}, and\n"
        "experimental search runners remain at \\textit{[anonymized repository]}.",
        "Paper sources, frozen figure JSONs, and build scripts are provided as anonymized supplementary material "
        "(\\texttt{hybridseam.zip}), and experimental search runners are in the \\texttt{HostSynth} subtree of the same archive.",
    )
    t = t.replace(
        "are published at \\textit{[anonymized repository]}\n"
        "under \\texttt{figures/} and \\texttt{results/}.",
        "are provided as anonymized supplementary material (\\texttt{hybridseam.zip})\n"
        "under \\texttt{figures/} and \\texttt{results/}.",
    )
    t = t.replace(
        "All experiments use the public procedural generators and open benchmarks in the released repository.",
        "All experiments use the public procedural generators and open benchmarks in the supplementary archive.",
    )
    return t

for f in sorted((ROOT / "subsections").glob("*.tex")):
    t = anonymise(f.read_text(encoding="utf-8"))
    t = re.sub(r"\\begin\{(figure|table|algorithm)\*\}", r"\\begin{\1}", t)
    t = re.sub(r"\\end\{(figure|table|algorithm)\*\}", r"\\end{\1}", t)
    t = t.replace("\\cite{", "\\citep{")
    # wide 8-column table laid out for the two-column page (overfull by 35 pt in the 6.5 in TMLR block)
    t = t.replace("\\label{tab:transfer-summary-main}\n  \\setlength{\\tabcolsep}{5pt}", "\\label{tab:transfer-summary-main}\n  \\setlength{\\tabcolsep}{2pt}")
    (out_sub / f.name).write_text(t, encoding="utf-8")
if not ACC:
    (out_sub / "acknowledgments.tex").write_text(
        "\\section*{Acknowledgments}\n\\label{sec:acknowledgments}\nWithheld for double-blind review.\n", encoding="utf-8")

used = set()
alltex = body + "".join(p.read_text(encoding="utf-8") for p in out_sub.glob("*.tex"))
for m in re.finditer(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]*)\}", alltex): used.add(m.group(1))
for m in re.finditer(r"\\input\{(figures/[^}]*)\}", alltex): used.add(m.group(1))
for u in sorted(used):
    p = ROOT / u
    cands = [p] if p.suffix else [p.with_suffix(e) for e in (".pdf", ".png", ".tex")]
    for c in cands:
        if c.exists():
            shutil.copy(c, out_fig / c.name)
            break
    else:
        print("WARNING missing figure", u)

name = "main_accepted.tex" if ACC else "main.tex"
# review variant: raster figures whose pixels carry identifying text are replaced by the sanitised copies
if not ACC:
    for f in sorted((HERE / "anon_figures").glob("*.png")):
        shutil.copy(f, out_fig / f.name)
(HERE / name).write_text(head + pre_doc + (body if ACC else review_rename(body)), encoding="utf-8")
print("wrote", HERE / name, "figures:", len(list(out_fig.iterdir())))
